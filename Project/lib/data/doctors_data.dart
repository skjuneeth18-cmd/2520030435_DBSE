/// Days that fall in the doctor's consulting week.
bool doctorConsultsOn(Doctor d, DateTime date) {
  const names = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  return d.consultationDays.contains(names[date.weekday - 1]);
}
